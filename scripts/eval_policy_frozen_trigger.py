"""
scripts/eval_policy_frozen_trigger.py -- Task 11 of the federated_optimizing_trigger_policy
review: chains federated_policy_to_flips -> federated_train_user on the .npz produced by
scripts/solve_policy_frozen_trigger.py (Task 10), and reports the downstream victim's CTA/ASR.

Four arms, SAME frozen 1xs stripe trigger, SAME flip budget, SAME aggregator ("mean"), SAME
seed:
  1. policy      -- u* from Task 10 (best lambda ratio), materialized via federated_policy_
                     to_flips.
  2. naive       -- u = beta_local * e_{source,target} in the SAME pairs ordering as the
                     policy .npz, no QP at all. The DECISIVE arm: if `policy` does not clear
                     `naive` by a real margin, the per-class QP policy adds nothing over a
                     plain source->target label flip under this frozen trigger.
  3. flip        -- the repo's existing FLIP baseline (trajectory-matched label selection, no
                     trigger optimization) -- an EXISTING, already-materialized flips
                     directory, pointed to via --flip-baseline-flips-dir (not regenerated by
                     this script: that pipeline has its own campaign/orchestration already).
  4. joint       -- federated_generate_labels_trigger_joint's trigger+labels -- an EXISTING,
                     already-materialized flips directory (--joint-flips-dir). NOT an
                     apples-to-apples comparison (it assumes dataset knowledge the frozen-
                     trigger arms don't use) -- reported as a ceiling reference, not a peer.

Does not modify any run_module.py: federated_policy_to_flips and federated_train_user are
invoked exactly as run_experiment.py would (extract_toml + that module's own run()), against
freshly-written config.toml files under experiments/<scratch>/ -- no reimplementation of
either module's own logic. Local execution only, no Slurm.

Also verifies and reports one specific point in federated_policy_to_flips (see
check_flip_selection_mechanism below): at a given mass u_{y,z}, HOW are the class-y examples
that get flipped chosen? materialize_policy_flips (federated_policy_to_flips/utils.py) draws
them from a SEEDED PER-CLASS SHUFFLE (numpy Generator.shuffle), not by index order and not by
an unseeded random draw -- the same mechanism both the `policy` and `naive` arms share, and
the most likely source of any gap against `flip` (arm 3), which instead selects via
trajectory-matching relevance, not a shuffle.

Usage:
    python scripts/eval_policy_frozen_trigger.py \
        --policy-npz out/solve_policy_frozen_trigger/policy_frozen_stripe_ratio0.5.npz \
        --budgets 500,1500 \
        --flip-baseline-flips-dir experiments/.../select_flips \
        --joint-flips-dir experiments/.../select_flips \
        --out out/eval_policy_frozen_trigger/results.json
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from modules.federated_policy_to_flips import run_module as policy_to_flips_run_module
from modules.federated_train_user import run_module as train_user_run_module

SCRATCH_ROOT = "eval_policy_frozen_trigger"

LEARNING_RATE = {"r32p": 0.1, "r18": 0.1, "vgg": 0.01}
WEIGHT_DECAY = {"r32p": 2e-4, "r18": 2e-4, "vgg": 2e-4}
MILESTONE = {"r32p": [75, 125], "r18": [75, 125], "vgg": [125]}

POLICY_TO_FLIPS_TEMPLATE = """[federated_policy_to_flips]
policy_path = "{policy_path}"
dataset = "{dataset}"
output_dir = "{output_dir}"
num_honests = {num_honests}
num_poisoned = {num_poisoned}
budget = {budget}
"""

TRAIN_USER_TEMPLATE = """[federated_train_user]
input_labels = "{flips_dir}/"
output_dir = "{train_user_dir}"
user_model = "{model_flag}"
trainer = "sgd"
dataset = "{dataset}"
source_label = {source_label}
target_label = {target_label}
poisoner = "1xs"
budget = {budget}
num_honests = {num_honests}
num_poisoned = {num_poisoned}
agg_method = "{agg_method}"
optim_kwargs = {{lr = {lr}, momentum = 0.9, nesterov = true, weight_decay = {wd}}}
schedule_kwargs = {{milestones = {milestones}, gamma = 0.1}}
"""


def write_config(experiment_name, module_name, content):
    path = Path("experiments") / experiment_name / "config.toml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return path


def check_flip_selection_mechanism():
    '''Task 11's verification point: prints, and returns, a description of HOW
    materialize_policy_flips (federated_policy_to_flips/utils.py) picks which class-y examples
    get flipped for a given mass u_{y,z} -- read directly from that function's own
    implementation, not inferred. See this script's own module docstring for the summary.'''
    note = (
        "materialize_policy_flips draws from a SEEDED PER-CLASS SHUFFLE "
        "(np.random.default_rng(seed).shuffle over each class y's example indices), then "
        "takes n_{y,c}=round(u_{y,c}*gamma*n_train) examples off the front of that shuffled "
        "pool per (y,c) pair IN `pairs` ORDER (a cursor advances across pairs sharing the "
        "same source class y, so no example is double-flipped); overflow (sum_c n_{y,c} > "
        "available class-y examples) silently clips the LATER pairs in `pairs` order. This is "
        "NOT index order and NOT trajectory-relevance-weighted -- it is the SAME mechanism for "
        "both the `policy` and `naive` arms below (both go through materialize_policy_flips), "
        "so it cannot explain a gap BETWEEN those two arms, but it IS a plausible source of a "
        "gap against `flip` (arm 3), which instead selects examples by trajectory-matching "
        "relevance, not a shuffle."
    )
    print(f"[selection mechanism] {note}")
    return note


def build_naive_npz(policy_npz_path, out_path):
    '''Arm 2: u = beta_local * e_{source,target} in the SAME `pairs` ordering as the policy
    .npz (loaded, not recomputed) -- everything else (beta, n_train, source/target,
    num_honests/num_poisoned, gamma) copied through unchanged so federated_policy_to_flips'
    own num_honests/num_poisoned cross-check (run_module.py) passes identically for both arms.'''
    npz = np.load(policy_npz_path)
    pairs = list(zip(npz["pairs_y"].tolist(), npz["pairs_c"].tolist()))
    source_label = int(npz["source_label"])
    target_label = int(npz["target_label"])
    beta = float(npz["beta"])
    idx_st = pairs.index((source_label, target_label))

    u_naive = np.zeros_like(npz["u"])
    u_naive[idx_st] = beta

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(
        out_path,
        u=u_naive.astype(np.float32),
        pairs_y=npz["pairs_y"],
        pairs_c=npz["pairs_c"],
        beta=npz["beta"],
        n_train=npz["n_train"],
        source_label=npz["source_label"],
        target_label=npz["target_label"],
        num_honests=npz["num_honests"],
        num_poisoned=npz["num_poisoned"],
        gamma=npz["gamma"],
    )
    return out_path


def get_final_value(npy_path):
    try:
        if not npy_path.exists() or npy_path.stat().st_size == 0:
            return np.nan
        data = np.load(npy_path, allow_pickle=True)
        if data.size == 0:
            return np.nan
        return float(data[-1][0]) if data.ndim > 1 else float(data[-1])
    except Exception:
        return np.nan


def run_policy_to_flips_and_train_user(
    arm_name, policy_npz_path, budget, dataset, model_flag, source_label, target_label,
    num_honests, num_poisoned, agg_method,
):
    tag = f"{arm_name}_budget{budget}"
    flips_experiment = f"{SCRATCH_ROOT}/{tag}/policy_to_flips"
    train_user_experiment = f"{SCRATCH_ROOT}/{tag}/train_user"

    flips_output_dir = str(Path("experiments") / flips_experiment / "out")
    write_config(
        flips_experiment, "federated_policy_to_flips",
        POLICY_TO_FLIPS_TEMPLATE.format(
            policy_path=str(policy_npz_path), dataset=dataset, output_dir=flips_output_dir,
            num_honests=num_honests, num_poisoned=num_poisoned, budget=budget,
        ),
    )
    policy_to_flips_run_module.run(flips_experiment, "federated_policy_to_flips")

    return run_train_user(
        train_user_experiment, flips_output_dir, budget, dataset, model_flag, source_label,
        target_label, num_honests, num_poisoned, agg_method,
    )


def run_train_user(
    train_user_experiment, flips_dir, budget, dataset, model_flag, source_label, target_label,
    num_honests, num_poisoned, agg_method,
):
    train_user_output_dir = str(Path("experiments") / train_user_experiment / "out")
    lr = LEARNING_RATE.get(model_flag, 0.1)
    wd = WEIGHT_DECAY.get(model_flag, 2e-4)
    milestones = MILESTONE.get(model_flag, [75, 125])
    write_config(
        train_user_experiment, "federated_train_user",
        TRAIN_USER_TEMPLATE.format(
            flips_dir=flips_dir, train_user_dir=train_user_output_dir, model_flag=model_flag,
            dataset=dataset, source_label=source_label, target_label=target_label,
            budget=budget, num_honests=num_honests, num_poisoned=num_poisoned,
            agg_method=agg_method, lr=lr, wd=wd, milestones=milestones,
        ),
    )
    train_user_run_module.run(train_user_experiment, "federated_train_user")

    out_dir = Path(train_user_output_dir)
    return {
        "cta": get_final_value(out_dir / "caccs.npy"),
        "asr": get_final_value(out_dir / "paccs.npy"),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--policy-npz", required=True, help="Task 10's .npz for the chosen ratio")
    parser.add_argument("--budgets", default="500,1500")
    parser.add_argument("--dataset", default="cifar")
    parser.add_argument("--model", default="r32p")
    parser.add_argument("--agg-method", default="mean")
    parser.add_argument(
        "--flip-baseline-flips-dir", default=None,
        help="existing federated_select_flips output dir for the repo's FLIP baseline "
             "(arm 3) -- must already contain {budget}_indices.npy/{budget}_labels.npy for "
             "every --budgets value. Omit to skip this arm.",
    )
    parser.add_argument(
        "--joint-flips-dir", default=None,
        help="existing federated_generate_labels_trigger_joint select_flips output dir "
             "(arm 4, ceiling reference, not apples-to-apples). Omit to skip this arm.",
    )
    parser.add_argument("--out", default="out/eval_policy_frozen_trigger/results.json")
    args = parser.parse_args()

    npz = np.load(args.policy_npz)
    source_label = int(npz["source_label"])
    target_label = int(npz["target_label"])
    num_honests = int(npz["num_honests"])
    num_poisoned = int(npz["num_poisoned"])

    selection_note = check_flip_selection_mechanism()

    naive_npz_path = build_naive_npz(
        args.policy_npz, Path("out") / SCRATCH_ROOT / "naive_flip.npz",
    )

    budgets = [int(b) for b in args.budgets.split(",")]
    results = {"selection_mechanism_note": selection_note, "arms": {}}

    for budget in budgets:
        print(f"\n{'=' * 20} budget={budget} {'=' * 20}")
        row = {}

        print("[arm: policy]")
        row["policy"] = run_policy_to_flips_and_train_user(
            "policy", args.policy_npz, budget, args.dataset, args.model, source_label,
            target_label, num_honests, num_poisoned, args.agg_method,
        )

        print("[arm: naive]")
        row["naive"] = run_policy_to_flips_and_train_user(
            "naive", naive_npz_path, budget, args.dataset, args.model, source_label,
            target_label, num_honests, num_poisoned, args.agg_method,
        )

        if args.flip_baseline_flips_dir:
            print("[arm: flip]")
            row["flip"] = run_train_user(
                f"{SCRATCH_ROOT}/flip_budget{budget}/train_user", args.flip_baseline_flips_dir,
                budget, args.dataset, args.model, source_label, target_label, num_honests,
                num_poisoned, args.agg_method,
            )
        else:
            row["flip"] = {"cta": None, "asr": None, "note": "no --flip-baseline-flips-dir given"}

        if args.joint_flips_dir:
            print("[arm: joint]")
            row["joint"] = run_train_user(
                f"{SCRATCH_ROOT}/joint_budget{budget}/train_user", args.joint_flips_dir,
                budget, args.dataset, args.model, source_label, target_label, num_honests,
                num_poisoned, args.agg_method,
            )
        else:
            row["joint"] = {"cta": None, "asr": None, "note": "no --joint-flips-dir given"}

        results["arms"][budget] = row

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nSaved: {out_path}")

    print(f"\n{'arm':<10} {'budget':>8} {'CTA':>10} {'ASR':>10}")
    for budget, row in results["arms"].items():
        for arm in ["policy", "naive", "flip", "joint"]:
            cta, asr = row[arm].get("cta"), row[arm].get("asr")
            cta_s = f"{cta:.4f}" if isinstance(cta, float) and not np.isnan(cta) else "n/a"
            asr_s = f"{asr:.4f}" if isinstance(asr, float) and not np.isnan(asr) else "n/a"
            print(f"{arm:<10} {budget:>8} {cta_s:>10} {asr_s:>10}")

    print(
        "\nDecisive comparison: 'naive' vs 'policy' at each budget. If 'policy' does not clear "
        "'naive' by a real ASR margin, the per-class QP policy is not adding anything over a "
        "plain source->target flip under this frozen trigger. 'flip' and 'joint' are reference "
        "points -- 'joint' in particular assumes strictly more (dataset-level trigger "
        "optimization), not a peer comparison."
    )
