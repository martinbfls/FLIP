def _cta_pta_mean_var(run_dir_fn, seeds, cta_file, pta_file):
    """Shared core: averages caccs.npy/paccs.npy's final value across `seeds`, for whatever
    single (budget, series-label) cell `run_dir_fn(seed)` resolves to. Used by both
    compute_cta_pta_mean_var (main campaign, series = agg_method) and
    compute_cta_pta_mean_var_gradmatch (gradmatch_metric campaign, series = gradmatch_metric)
    below -- the only thing that differs between campaigns is how a cell's directory is built,
    not how its outputs are read/averaged."""
    cta_vals, pta_vals = [], []
    for seed in seeds:
        run_dir = run_dir_fn(seed)
        cta_path = run_dir / cta_file
        pta_path = run_dir / pta_file
        if not (cta_path.exists() and pta_path.exists()):
            continue
        cta_vals.append(get_final_value(cta_path))
        pta_vals.append(get_final_value(pta_path))

    return (
        np.mean(cta_vals) if cta_vals else np.nan,
        np.var(cta_vals) if cta_vals else np.nan,
        np.mean(pta_vals) if pta_vals else np.nan,
        np.var(pta_vals) if pta_vals else np.nan,
    )


def compute_cta_pta_mean_var(
    model_flag,
    dataset,
    agg_method,
    budgets,
    seeds,
    cta_file="caccs.npy",
    pta_file="paccs.npy",
):
    """Reads federated_train_user's outputs for each (budget, seed) cell of the MAIN
    (3-poisoned/7-honest, agg_method-swept) threat_model_direct_trigger_joint campaign.
    Directory layout matches gen_configs.generate_cell() exactly: EXP_BASE / cell_name(...) /
    train_user_{budget}/{caccs,paccs}.npy -- cell_name() is imported straight from
    gen_configs.py so this can't drift from wherever the configs actually got written.
    """
    records = []

    for budget in budgets:
        run_dir_fn = lambda seed, budget=budget: (
            EXP_BASE / cell_name(model_flag, dataset, agg_method, seed) / f"train_user_{budget}"
        )
        cta_mean, cta_var, pta_mean, pta_var = _cta_pta_mean_var(
            run_dir_fn, seeds, cta_file, pta_file
        )
        records.append(
            {
                "dataset": dataset,
                "aggregator": agg_method,
                "budget": budget,
                "model": model_flag,
                "cta_mean": cta_mean,
                "cta_var": cta_var,
                "pta_mean": pta_mean,
                "pta_var": pta_var,
            }
        )

    return pd.DataFrame.from_records(records)


