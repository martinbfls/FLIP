def trigger_path_in(module_dir, model_flag, dataset, num_poisoned, num_honests, init="stripe"):
    """Path to the .pt trigger written by federated_generate_labels_trigger_joint's
    run_module.py (torch.save(delta, ...), see its `trig_path` build) INSIDE a given
    `module_dir` (a campaign's .../gen_labels_trigger_joint directory). Filename convention is
    f"..._{{{init}}}_..." with run_tag=f"{num_poisoned}vs{num_honests}" -- `init` (2026-09-01,
    "stripe" or "random", see gen_configs.py's own INIT/gen_configs_init_compare.py) and
    num_poisoned/num_honests both vary by campaign, so both are passed explicitly rather than
    assumed."""
    return (
        module_dir
        / "trigger"
        / f"opt_trig_direct_joint_{init}_{model_flag}_{dataset}_{num_poisoned}vs{num_honests}.pt"
    )


def check_epsilon_compliance(
    module_dir, model_flag, dataset, num_poisoned, num_honests, epsilon, init="stripe",
    tol=1e-6,
):
    """Loads the saved trigger .pt and reports the measured L_infinity norm
    (delta.abs().max()) against the `epsilon` this cell was configured with -- a direct,
    numeric check that run_module.py's per-step `delta.clamp_(-epsilon, epsilon)` (or the
    "projection" branch's Linf-ball projection, see project_trigger_constraints) actually held
    for the FINAL saved delta, instead of eyeballing PNGs where a small epsilon's effect can be
    visually subtle. Returns None if the .pt doesn't exist yet (same graceful-skip convention
    as save_trigger_visual_in); otherwise returns (measured_linf, epsilon, within_bound: bool).
    within_bound uses `tol` slack for float rounding -- anything measured > epsilon + tol would
    mean the hard constraint was violated (a real bug), not just "hard to see"."""
    trig_path = trigger_path_in(
        module_dir, model_flag, dataset, num_poisoned, num_honests, init=init,
    )
    if not trig_path.exists():
        return None

    delta = torch.load(trig_path, map_location="cpu")
    measured_linf = delta.abs().max().item()
    within_bound = measured_linf <= epsilon + tol

    status = "OK" if within_bound else "VIOLATION"
    print(
        f"[EPSILON CHECK] {trig_path.parent.parent.name}: measured max|delta|="
        f"{measured_linf:.6f} vs configured epsilon={epsilon:.6f} -- {status}"
    )
    return measured_linf, epsilon, within_bound


def save_trigger_visual_in(
    module_dir, model_flag, dataset, num_poisoned, num_honests, label, sample_seed=0,
    init="stripe",
):
    """Renders clean-vs-poisoned side by side for one generated trigger and saves the PNG next
    to the .pt file itself (same `trigger/` directory). `label` is used as-is for the poisoned
    panel's subtitle (e.g. "mean, seed0" for the main campaign, "cosine, seed0" for the
    gradmatch_metric comparison, "random, seed0" for the init comparison) -- this function
    itself has no notion of which campaign/axis produced it."""
    trig_path = trigger_path_in(
        module_dir, model_flag, dataset, num_poisoned, num_honests, init=init,
    )
    if not trig_path.exists():
        return None

    dataset_obj = load_dataset(dataset, train=True)
    indices = [i for i, (_, y) in enumerate(dataset_obj) if y == SOURCE_LABEL]
    idx = np.random.RandomState(sample_seed).choice(indices)
    img, _ = dataset_obj[idx]

    clean_img = img
    if isinstance(clean_img, torch.Tensor):
        clean_img = transforms.ToPILImage()(clean_img)

    poisoner = pick_poisoner("optimized", dataset, TARGET_LABEL, delta=str(trig_path))
    poisoned_img, _ = poisoner.poison((img, SOURCE_LABEL))
    if isinstance(poisoned_img, torch.Tensor):
        poisoned_img = transforms.ToPILImage()(poisoned_img)

    fig, axes = plt.subplots(1, 2, figsize=(6, 3.2))
    axes[0].imshow(clean_img)
    axes[0].set_title("Clean image", fontsize=11)
    axes[0].axis("off")
    axes[1].imshow(poisoned_img)
    axes[1].set_title(f"Poisoned ({label})", fontsize=11)
    axes[1].axis("off")
    plt.tight_layout()

    out_path = trig_path.with_suffix(".png")
    fig.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"[INFO] Saved trigger visual: {out_path}")
    return out_path


