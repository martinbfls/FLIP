"""
Results reader for federated_optimizing_trigger_policy campaigns generated by
modules/federated_optimizing_trigger_policy/gen_configs.py.

For each (model_flag, dataset, budget_target, seed) cell of the campaign's own sweep axes
(read directly from gen_configs.py, so this always looks in the same places the campaign
actually wrote to), reports three things at three different levels:

  1. metrics.json      -- per-outer-step loss history (B2, L_bd, B2_qp, clean_acc/poison_acc
                           measured on the SAME model used during trigger/policy optimization
                           -- a cheap proxy, not the real downstream attack).
  2. diagnostics.jsonl -- the optimization/feasibility diagnostics. diagnose() below applies
                           the decision tree from modules/federated_optimizing_trigger_policy/
                           diagnostics.py's own module docstring to the LAST diagnosed batch and
                           prints plain-English findings; read that docstring directly for the
                           full chain and for records this doesn't flag anything on.
  3. train_user_<budget>/{caccs,paccs}.npy -- the REAL downstream attack performance (a fresh
                           user model trained on the materialized flips), same convention as
                           the other threat-model modules' show_results.py.

Usage: python show_results_policy.py
"""
import json

import numpy as np

from modules.federated_optimizing_trigger_policy.gen_configs import (
    BUDGETS_TARGET,
    DATASETS,
    EXP_BASE,
    MODEL_FLAGS,
    NUM_HONESTS,
    NUM_POISONED,
    SEEDS,
    cell_name,
    resolve_beta_gamma,
)

_PI_MIN_APPROX = 1.0 / 10  # CIFAR-family: 10 balanced classes -- same approximation
# gen_configs.py's generate_cell() uses for s_beta.


def get_final_value(npy_path):
    try:
        if not npy_path.exists() or npy_path.stat().st_size == 0:
            return np.nan
        data = np.load(npy_path, allow_pickle=True)
        if data.size == 0:
            return np.nan
        return float(data[-1][0]) if data.ndim > 1 else float(data[-1])
    except Exception:
        return np.nan


def cell_paths(model_flag, dataset, seed, budget_target):
    cell_dir = EXP_BASE / cell_name(model_flag, dataset, seed, budget_target)
    beta_local, gamma, beta_global, n_train = resolve_beta_gamma(
        budget_target, dataset, NUM_POISONED, NUM_HONESTS,
    )
    n_w = NUM_POISONED + NUM_HONESTS
    # Same formula gen_configs.py's generate_cell() uses to name the train_user dir --
    # federated_train_user's budget is DERIVED, not a free choice, for this module.
    predicted_budget = round(beta_local * NUM_POISONED * n_train / n_w)
    s_beta = beta_global / (gamma * _PI_MIN_APPROX)
    return {
        "cell_dir": cell_dir,
        "policy_dir": cell_dir / "policy_opt",
        "flips_dir": cell_dir / "policy_to_flips",
        "train_user_dir": cell_dir / f"train_user_{predicted_budget}",
        "predicted_budget": predicted_budget,
        "beta_local": beta_local,
        "beta_global": beta_global,
        "gamma": gamma,
        "s_beta": s_beta,
    }


def load_metrics(policy_dir):
    path = policy_dir / "metrics.json"
    if not path.exists():
        return None
    with open(path) as f:
        return json.load(f)


def load_diagnostics(policy_dir):
    path = policy_dir / "diagnostics.jsonl"
    if not path.exists():
        return []
    records = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def diagnose(record):
    """Applies diagnostics.py's module-docstring decision tree to one diagnostics.jsonl
    record. Returns a list of plain-English findings; empty checks are silently skipped (a
    missing field means that diagnostic wasn't enabled for this campaign, see gen_configs.py's
    DIAG_* constants) -- read diagnostics.py's docstring directly for anything not flagged
    here."""
    findings = []

    b2 = record.get("B2_current_continuous")
    b2_qp = record.get("B2_qp_continuous")
    if b2 is not None and b2_qp is not None and abs(b2_qp) > 1e-8:
        ratio = b2 / b2_qp
        if ratio > 1.5:
            findings.append(
                f"B2={b2:.4g} vs B2_qp={b2_qp:.4g} (ratio {ratio:.2f}x): u is lagging delta -- "
                "an OPTIMIZATION problem (try lr_policy / n_steps / policy_inner_mode), not a "
                "feasibility one."
            )

    span = record.get("B2_span")
    if span is not None and b2_qp is not None and abs(b2_qp) > 1e-8:
        if span / b2_qp > 0.7:
            findings.append(
                f"B2_span={span:.4g} is close to B2_qp={b2_qp:.4g}: even the fully "
                "unconstrained best combination of flip-gradient columns can't track v(delta) "
                "-- a genuine subspace-coverage limitation (change delta or the (source, "
                "target) pairs), not a constraint effect."
            )
        elif span < 0.3 * b2_qp:
            if record.get("qp_global_budget_active"):
                findings.append(
                    f"B2_span={span:.4g} << B2_qp={b2_qp:.4g}, and the global flip budget is "
                    "ACTIVE at the QP optimum: the CONSTRAINT set (not the flip gradients' "
                    "span) is limiting the attack -- sweeping beta/the budget may help."
                )
            if record.get("qp_any_class_cap_active"):
                findings.append(
                    f"B2_span={span:.4g} << B2_qp={b2_qp:.4g}, and a per-class cap is ACTIVE "
                    f"(active caps: {record.get('qp_active_class_caps')}): that source class "
                    "is out of examples to flip -- no beta sweep fixes this."
                )

    cos_qp_v = record.get("cosine_scaled_qp") or record.get("cosine_qp")
    res_after_scale = record.get("residual_after_optimal_scaling_qp")
    res_qp = record.get("qp_residual")
    if cos_qp_v is not None and cos_qp_v > 0.95 and res_after_scale is not None and res_qp:
        if res_after_scale < 0.5 * res_qp:
            findings.append(
                f"cosine~={cos_qp_v:.3f} but residual drops from {res_qp:.4g} to "
                f"{res_after_scale:.4g} after optimal rescaling: an AMPLITUDE-only mismatch -- "
                "the QP policy already points the right way, it just can't reach the right "
                "magnitude under U_loc (consistent with the budget being active)."
            )

    disc_gap_rel = record.get("discretization_gap_qp_relative")
    if disc_gap_rel is not None and disc_gap_rel > 0.3:
        findings.append(
            f"discretization_gap_qp_relative={disc_gap_rel:.2%}: rounding the continuous QP "
            "optimum into integer flip counts destroys much of the alignment -- compare "
            "qp_nnz_requested vs qp_nnz_after_rounding (u spread thin over many pairs?)."
        )

    grad_ratio = record.get("grad_delta_ratio")
    if grad_ratio is not None:
        if grad_ratio > 3:
            findings.append(
                f"grad_delta_ratio={grad_ratio:.2f} (||grad B2|| >> ||grad L_bd||): the B2 "
                "matching term dominates delta's own gradient -- a LOSS-BALANCE problem; "
                "lambda_bd may be too small relative to B2's scale for delta to actually learn "
                "to backdoor."
            )
        elif grad_ratio < 0.33:
            findings.append(
                f"grad_delta_ratio={grad_ratio:.2f} (||grad L_bd|| >> ||grad B2||): delta is "
                "barely responding to the matching term B2 -- consider raising lambda_b2 if "
                "the policy's own performance (B2/B2_qp above) also looks poor."
            )

    for key, value in record.items():
        if key.startswith("qp_") and key.endswith("_relative_improvement") and value is not None:
            if abs(value) > 0.05:
                findings.append(
                    f"{key}={value:.2%}: the QP diagnostic itself had not converged between "
                    "these check_iters -- B2_qp may be optimistic (under-converged); re-check "
                    "with a larger diag_qp_iters before trusting comparisons against it."
                )

    if not findings:
        findings.append(
            "No red flag found in this record against the standard checks above -- see "
            "diagnostics.py's module docstring for the full decision tree / fields not "
            "covered here."
        )
    return findings


def summarize_cell(model_flag, dataset, seed, budget_target):
    paths = cell_paths(model_flag, dataset, seed, budget_target)
    print(f"\n=== {model_flag}/{dataset} seed={seed} budget_target={budget_target} ===")
    print(f"cell_dir: {paths['cell_dir']}")
    print(
        f"beta_local={paths['beta_local']:.6f} beta_global={paths['beta_global']:.6f} "
        f"gamma={paths['gamma']:.4f} s_beta={paths['s_beta']:.4f}"
        f"{' (SATURATED)' if paths['s_beta'] > 1 else ''}"
    )

    metrics = load_metrics(paths["policy_dir"])
    if metrics:
        last = metrics[-1]
        print(f"\n-- metrics.json ({len(metrics)} outer step(s), showing the last) --")
        for key in [
            "step", "clean_acc", "poison_acc", "B2", "L_bd", "B2_qp",
            "lambda_effective", "lambda_effective_ratio",
        ]:
            if key in last:
                print(f"  {key}: {last[key]}")
    else:
        print(f"\n-- metrics.json: not found at {paths['policy_dir']}/metrics.json --")

    diag_records = load_diagnostics(paths["policy_dir"])
    if diag_records:
        print(f"\n-- diagnostics.jsonl ({len(diag_records)} diagnosed batch(es)) --")
        print("Diagnosis of the LAST diagnosed batch:")
        for finding in diagnose(diag_records[-1]):
            print(f"  - {finding}")
    else:
        print(f"\n-- diagnostics.jsonl: not found or empty at {paths['policy_dir']} --")

    cta = get_final_value(paths["train_user_dir"] / "caccs.npy")
    asr = get_final_value(paths["train_user_dir"] / "paccs.npy")
    print(f"\n-- train_user_{paths['predicted_budget']} (downstream attack, ground truth) --")
    print(f"  CTA (clean test accuracy) = {cta}")
    print(f"  ASR (poison/attack success rate) = {asr}")


if __name__ == "__main__":
    for model_flag in MODEL_FLAGS:
        for dataset in DATASETS:
            for budget_target in BUDGETS_TARGET:
                for seed in SEEDS:
                    summarize_cell(model_flag, dataset, seed, budget_target)
